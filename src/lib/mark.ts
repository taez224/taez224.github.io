// 격자를 가로로 이어 붙인 사각형 경로로 바꾼다. 칸마다 사각형을 하나씩 두면 인장 하나가 300칸이 넘어 마크업이 본문보다 길어진다.
export function markPath(grid: readonly string[]): string {
  let path = '';
  grid.forEach((row, y) => {
    let run = 0;
    for (let x = 0; x <= row.length; x += 1) {
      if (row[x] === '#') { run += 1; continue; }
      if (run > 0) path += `M${x - run} ${y}h${run}v1h-${run}z`;
      run = 0;
    }
  });
  return path;
}
